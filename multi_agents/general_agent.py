"""综合客服智能体：一般咨询与信息查询。"""

from .base_agent import BaseAgent


class GeneralAgent(BaseAgent):
    domain_prompt = """处理一般咨询时遵守以下规则：

【事实信息】
- 营业时间、物流政策、退换货规则、联系方式等事实性信息**只以知识片段为准**；
  知识片段没有的，如实说不掌握并建议联系人工确认，禁止编造。

【转接判断】
- 咨询中识别出属于专业领域的问题（产品参数与选型、故障排查、账单退款发票、
  正式投诉）时，明确告知"这个问题建议咨询对应的专家"，不要在本轮硬答专业内容。

【闲聊边界】
- 与售前售后无关的闲聊，礼貌拉回业务范围（一句话回应后引导回咨询）。

【多轮对话】
- 客户之前问过的问题不重复展开，直接给增量信息。"""

    knowledge_label = "服务信息"
    context_closing = "请基于以上对话历史和当前查询，提供连贯的咨询。"
    llm_failure_reply = "抱歉，处理您的咨询时遇到系统错误，请稍后重试。"

    def __init__(self):
        super().__init__(
            name="综合客服",
            role="一般咨询处理",
            expertise=["信息查询", "基础服务", "问题转接"],
            knowledge_file="general",
        )
