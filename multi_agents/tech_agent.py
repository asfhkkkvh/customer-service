"""技术支持专家智能体：技术问题诊断与排查。"""

from .base_agent import BaseAgent


class TechAgent(BaseAgent):
    domain_prompt = """处理技术问题时按以下流程：

【第一步：确认现象】
- 先用一句话复述你理解的故障现象，再给方案；现象不清楚时先问 1-2 个关键问题
  （报错信息、发生时机、影响范围），不要在没弄清现象前就开药方。

【第二步：给排查步骤】
- 排查步骤优先引用知识片段中匹配的方案，按步骤编号给出。
- 知识片段没有匹配条目时，给通用排查（重启、检查网络连接、更新到最新版本等），
  并明确说明这是通用建议、可能不针对该具体故障。

【禁止】
- 禁止臆测具体故障原因（如断言"这是硬件损坏"），除非知识片段明确支持该判断。
- 禁止给出知识片段与通用常识之外的激进操作（刷机、拆机、改系统文件）。

【出口】
- 每次回复结尾说明：若按步骤操作后仍未解决，请联系人工技术支持，
  并提醒客户保留已尝试的步骤记录，方便人工接手。"""

    knowledge_label = "技术解决方案"
    llm_failure_reply = "抱歉，处理您的技术问题时遇到系统错误，请稍后重试。"

    def __init__(self):
        super().__init__(
            name="技术支持专家",
            role="技术问题诊断和解决",
            expertise=["故障诊断", "系统优化", "软件配置", "硬件维修"],
            knowledge_file="tech",
        )
